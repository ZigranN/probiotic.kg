// ==========================================
// HELPERS
// ==========================================

function getArticle(slug: string): Article | null {
    return ARTICLES[slug as keyof typeof ARTICLES] ?? null;
}

// ==========================================
// METADATA
// ==========================================

export async function generateMetadata({
                                           params,
                                       }: {
    params: Promise<{ slug: string }>;
}): Promise<Metadata> {
    const { slug } = await params;

    const article = getArticle(slug);

    if (!article) {
        return {
            title: "Материал не найден | probiotic.kg",

            robots: {
                index: false,
                follow: false,
            },
        };
    }

    const canonical = `/blog/${slug}`;

    return {
        title: article.title,

        description: article.description,

        alternates: {
            canonical,
        },

        openGraph: {
            type: "article",
            locale: "ru_KG",
            siteName: seller.siteName,

            title: article.title,
            description: article.description,

            url: canonical,
        },

        twitter: {
            card: "summary",
            title: article.title,
            description: article.description,
        },
    };
}

